"""Contrato público do módulo; DTOs são cópias das informações do negócio."""

from typing import Protocol, runtime_checkable
from server.shared.validation import NAO_INFORMADO


@runtime_checkable
class ComunidadeAPI(Protocol):
    def cadastrar_evento(self, titulo, quando, local, capacidade=None, lembrar_em=None) -> dict: ...
    def eventos(self, cliente_id=None) -> list[dict]: ...
    def inscrever(self, cliente_id, evento_id) -> dict: ...
    def criar_clube(self, nome) -> dict: ...
    def participar_clube(self, cliente_id, clube_id) -> dict: ...
    def publicar_opiniao(self, cliente_id, clube_id, texto) -> dict: ...
    def clubes(self, cliente_id) -> list[dict]: ...
    def processar_lembretes(self) -> None: ...
