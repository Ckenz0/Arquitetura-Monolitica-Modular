"""Contrato público do módulo; DTOs são cópias das informações do negócio."""

from typing import Protocol, runtime_checkable
from server.shared.validation import NAO_INFORMADO


@runtime_checkable
class FidelidadeAPI(Protocol):
    def registrar_compra(self, cliente_id, livro_id, pontos, expira_em=None, avisar_em=None) -> dict: ...
    def historico(self, cliente_id) -> list[dict]: ...
    def fidelidade(self, cliente_id) -> dict: ...
    def conceder_cupom(self, cliente_id, codigo, termos) -> dict: ...
    def recomendacoes(self, cliente_id) -> list[dict]: ...
    def processar_lembretes(self) -> None: ...
