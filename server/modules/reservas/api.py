"""Contrato público do módulo; DTOs são cópias das informações do negócio."""

from typing import Protocol, runtime_checkable
from server.shared.validation import NAO_INFORMADO


@runtime_checkable
class ReservasAPI(Protocol):
    def reservar(self, cliente_id, livro_id, prazo, embrulho=False) -> dict: ...
    def reservas(self, cliente_id) -> list[dict]: ...
    def alterar_prazo(self, cliente_id, reserva_id, prazo) -> dict: ...
    def cancelar_reserva(self, cliente_id, reserva_id) -> dict: ...
    def marcar_pronta(self, reserva_id) -> dict: ...
