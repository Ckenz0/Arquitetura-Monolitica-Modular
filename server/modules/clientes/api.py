"""Contrato público do módulo; DTOs são cópias das informações do negócio."""

from typing import Protocol, runtime_checkable
from server.shared.validation import NAO_INFORMADO


@runtime_checkable
class ClientesAPI(Protocol):
    def obter_perfil(self, cliente_id) -> dict: ...
    def preferencias(self, cliente_id, generos=NAO_INFORMADO, temas_notificacao=NAO_INFORMADO) -> dict: ...
    def notificar(self, cliente_id, tema, mensagem) -> None: ...
    def notificacoes(self, cliente_id) -> list[dict]: ...
    def listar_clientes(self) -> list[dict]: ...
