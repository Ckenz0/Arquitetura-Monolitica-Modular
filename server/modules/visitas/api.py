"""Contrato público do módulo; DTOs são cópias das informações do negócio."""

from typing import Protocol, runtime_checkable
from server.shared.validation import NAO_INFORMADO


@runtime_checkable
class VisitasAPI(Protocol):
    def entrar_fila(self, cliente_id) -> dict: ...
    def fila(self, cliente_id) -> dict: ...
    def oferecer_horario(self, livreiro, quando) -> dict: ...
    def agendar(self, cliente_id, horario_id) -> dict: ...
    def horarios(self) -> list[dict]: ...
    def agendamentos(self, cliente_id) -> list[dict]: ...
    def configurar_loja(self, horario, lotacao) -> None: ...
    def informacoes_loja(self) -> dict: ...
