"""Contrato público do módulo; DTOs são cópias das informações do negócio."""

from typing import Protocol, runtime_checkable
from server.shared.validation import NAO_INFORMADO


@runtime_checkable
class CatalogoAPI(Protocol):
    def livro(self, livro_id, cliente_id=None) -> dict: ...
    def buscar(self, q='', genero='', lancamentos=False) -> list[dict]: ...
    def por_codigo(self, codigo) -> dict: ...
    def buscar_por_titulo(self, titulo) -> list[dict]: ...
    def buscar_por_autor(self, autor) -> list[dict]: ...
    def filtrar_por_genero(self, genero) -> list[dict]: ...
    def consultar_estoque(self, titulo) -> int: ...
    def listar_lancamentos(self) -> list[dict]: ...
    def reservar_exemplar(self, livro_id, embrulho=False) -> dict: ...
    def devolver_exemplar(self, livro_id) -> dict: ...
    def acompanhar_estoque(self, cliente_id, livro_id) -> dict: ...
    def atualizar_estoque(self, livro_id, quantidade) -> dict: ...
    def adicionar_desejo(self, cliente_id, livro_id) -> dict: ...
    def desejos(self, cliente_id) -> list[dict]: ...
    def publicar_avaliacao(self, cliente_id, livro_id, nota, texto) -> dict: ...
